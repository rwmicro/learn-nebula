// Bundle the note-page enhancer scripts into a single request (note.bundle.js).
// esbuild resolves ES imports, so scripts can share modules from lib/ with the
// React side rather than keeping a second copy here.
// Each source stays a self-contained IIFE; esbuild scopes them per-module and
// runs them in the order below. Regenerated on `predev`/`build`; output is
// git-ignored.
import { build } from "esbuild";
import { join } from "node:path";

const JS_DIR = join(process.cwd(), "public", "js");

// Order mirrors components/NoteScripts.tsx. Turnstile stays a separate external
// <script>; i18n/instantpage/lightbox stay global (loaded site-wide in layout).
const SCRIPTS = [
  "toc",
  "audio",
  "font-size",
  "wide-text",
  "translate",
  "aside-toggle",
  "sticky-header",
  // After sticky-header: marks the note read / remembers the position, with
  // the same progress measure (lib/reading-progress.ts).
  "reading-state",
  "mermaid-render",
  // Not "widgets": the library itself is fetched on demand by the loader, for
  // the 30 notes out of 721 that actually mount one. public/js/widgets.js is
  // served as its own file (like mermaid.min.js) and never enters this bundle.
  "widgets-loader",
  "scroll-focus",
  "related",
  "comments",
  "youtube",
  "popover",
  "copy-links",
  "selection-menu",
  // After selection-menu: draws the highlights it creates ("Surligner").
  "highlights",
  // Back to top, section + time left, "Et ensuite ?", bookmark, focus mode,
  // reading shortcuts (n/p/t/s/f/b).
  "reader-tools",
];
// Not "quiz" nor "glossary": each is its own small bundle (quiz.bundle.js,
// glossary.bundle.js, built below) that components/NoteScripts.tsx adds only
// to the notes whose HTML has a `[!quiz]` card or a glossary mark — most
// notes have neither, and quiz.js alone pulls lib/note-quiz.ts + lib/srs.ts.
// Note: "ask" (the old floating note assistant) was removed — the note "AI"
// button now opens the single, draggable <PinnedAssistant> mounted site-wide.
// public/js/ask.js went with it; its .ask-* rules in main.css are now dead.

await build({
  // Synthetic entry that side-effect-imports each enhancer in order.
  stdin: {
    contents: SCRIPTS.map((s) => `import "./${s}.js";`).join("\n") + "\n",
    resolveDir: JS_DIR,
    loader: "js",
  },
  outfile: join(JS_DIR, "note.bundle.js"),
  bundle: true,
  format: "iife",
  target: ["es2020"],
  minify: true,
  legalComments: "none",
  banner: {
    js: "/* AUTO-GENERATED by scripts/bundle-js.mjs (esbuild) — do not edit. */",
  },
});

console.log(`bundle-js: bundled ${SCRIPTS.length} scripts → public/js/note.bundle.js`);

// Stand-alone bundles: the command palette (⌘K / Ctrl+K) runs on every page,
// so it is loaded from app/layout.tsx rather than being part of the note
// bundle — bundled (not served raw like theme.js) to share
// lib/palette-match.ts. quiz and glossary are per-note opt-ins (see above).
for (const name of ["palette", "quiz", "glossary"]) {
  await build({
    entryPoints: [join(JS_DIR, `${name}.js`)],
    outfile: join(JS_DIR, `${name}.bundle.js`),
    bundle: true,
    format: "iife",
    target: ["es2020"],
    minify: true,
    legalComments: "none",
    banner: {
      js: "/* AUTO-GENERATED by scripts/bundle-js.mjs (esbuild) — do not edit. */",
    },
  });
  console.log(`bundle-js: public/js/${name}.js → public/js/${name}.bundle.js`);
}
