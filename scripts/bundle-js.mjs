// Bundle the note-page enhancer scripts into a single request (note.bundle.js).
// esbuild resolves ES imports, so scripts can share modules (e.g. ask.js pulls
// readAskStream from lib/ask-stream.ts, shared with the React home assistant).
// Each source stays a self-contained IIFE; esbuild scopes them per-module and
// runs them in the order below. Regenerated on `predev`/`build`; output is
// git-ignored.
import { build } from "esbuild";
import { join } from "node:path";

const JS_DIR = join(process.cwd(), "public", "js");

// Order mirrors components/NoteScripts.tsx. Turnstile stays a separate external
// <script>; i18n/instantpage/lightbox stay global (loaded site-wide in layout).
const SCRIPTS = [
  "toc",
  "audio",
  "pronounce",
  "font-size",
  "wide-text",
  "translate",
  "aside-toggle",
  "sticky-header",
  "mermaid-render",
  "comments",
  "ask",
];

await build({
  // Synthetic entry that side-effect-imports each enhancer in order.
  stdin: {
    contents: SCRIPTS.map((s) => `import "./${s}.js";`).join("\n") + "\n",
    resolveDir: JS_DIR,
    loader: "js",
  },
  outfile: join(JS_DIR, "note.bundle.js"),
  bundle: true,
  format: "iife",
  target: ["es2020"],
  minify: true,
  legalComments: "none",
  banner: {
    js: "/* AUTO-GENERATED by scripts/bundle-js.mjs (esbuild) — do not edit. */",
  },
});

console.log(`bundle-js: bundled ${SCRIPTS.length} scripts → public/js/note.bundle.js`);
