// Bundle the note-page enhancer scripts into a single request (note.bundle.js).
// esbuild resolves ES imports, so scripts can share modules from lib/ with the
// React side rather than keeping a second copy here.
// Each source stays a self-contained IIFE; esbuild scopes them per-module and
// runs them in the order below. Regenerated on `predev`/`build`; output is
// git-ignored.
import { build } from "esbuild";
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { HASHED_SCRIPTS, hashedScriptName } from "../lib/hashed-scripts.js";

const JS_DIR = join(process.cwd(), "public", "js");

// Order mirrors components/NoteScripts.tsx. Turnstile stays a separate external
// <script>; i18n/lightbox stay global (loaded site-wide in layout).
const SCRIPTS = [
  "toc",
  "audio",
  "font-size",
  "wide-text",
  "translate",
  "aside-toggle",
  "sticky-header",
  // After sticky-header: marks the note read / remembers the position, with
  // the same progress measure (lib/reading-progress.ts).
  "reading-state",
  // Fetches diagram-zoom ("Agrandir", full-screen pan / zoom) and the
  // mermaid-render fallback, each its own bundle, only on a note with a diagram.
  "diagrams-loader",
  // Not "widgets": the library itself is fetched on demand by the loader, for
  // the 30 notes out of 721 that actually mount one. public/js/widgets.js is
  // served as its own file (like mermaid.min.js) and never enters this bundle.
  "widgets-loader",
  // ```iso:<name>``` figures: syncs their theme, then imports
  // /figures/<name>.js (scripts/build-figures.mjs) only on a page with one.
  "iso-figures",
  "scroll-focus",
  "related",
  "comments",
  "youtube",
  "popover",
  "copy-links",
  // "Citer cette note" under the article: copy buttons, today's date.
  "cite",
  "selection-menu",
  // After selection-menu: draws the highlights it creates ("Surligner").
  "highlights",
  // Back to top, section + time left, "Et ensuite ?", bookmark, focus mode,
  // reading shortcuts (n/p/t/s/f/b).
  "reader-tools",
  // On a note of a reading path: "Étape suivante" pinned bottom left.
  "path-dock",
  // On a note of a reading path: "Étape 4/20" opens the list of its steps.
  "path-sheet",
  // Under the article: "Défier quelqu'un" (duel) / "Lancer un tandem" → /duel/.
  "duo-invite",
  // Last: the phone layout's section pill, toolbar and display sheet proxy
  // the controls the scripts above wire up.
  "note-app",
  // From 640px up: the floating reading bar (liquid glass) that shrinks while
  // scrolling down.
  "note-dock",
];
// Not "quiz" nor "glossary": each is its own small bundle (quiz.bundle.js,
// glossary.bundle.js, built below) that components/NoteScripts.tsx adds only
// to the notes whose HTML has a `[!quiz]` card or a glossary mark — most
// notes have neither, and quiz.js alone pulls lib/note-quiz.ts + lib/srs.ts.
// Note: "ask" (the old floating note assistant) was removed — the note "AI"
// button now opens the single, draggable <PinnedAssistant> mounted site-wide.
// public/js/ask.js went with it; its .ask-* rules in main.css are now dead.

await build({
  // Synthetic entry that side-effect-imports each enhancer in order.
  stdin: {
    contents: SCRIPTS.map((s) => `import "./${s}.js";`).join("\n") + "\n",
    resolveDir: JS_DIR,
    loader: "js",
  },
  outfile: join(JS_DIR, "note.bundle.js"),
  bundle: true,
  format: "iife",
  target: ["es2020"],
  minify: true,
  legalComments: "none",
  banner: {
    js: "/* AUTO-GENERATED by scripts/bundle-js.mjs (esbuild) — do not edit. */",
  },
});

console.log(`bundle-js: bundled ${SCRIPTS.length} scripts → public/js/note.bundle.js`);

// Stand-alone bundles: the command palette (⌘K / Ctrl+K) runs on every page,
// so it is loaded from app/layout.tsx rather than being part of the note
// bundle — bundled (not served raw like theme.js) to share
// lib/palette-match.ts. quiz and glossary are per-note opt-ins (see above),
// note-end (the phone's "Lue !" card) too: only notes of a reading path.
// The widget packs (lib/widgets-extra.ts): fetched by widgets-loader.js only
// on a page that mounts one of their widgets. Bundled so they share
// public/js/widget-kit.js and lib/ code with the build.
// pronounce: fetched by pronounce-loader.js on a page with a clip; bundled
// for lib/speech-match.ts (the coach's on-device "reconnu / pas reconnu").
// diagram-zoom / mermaid-render: fetched by diagrams-loader.js on a note with a
// diagram; mermaid-render is bundled for lib/mermaid-source.js.
for (const name of ["palette", "quiz", "glossary", "note-end", "widgets-data", "widgets-sci", "widgets-lang", "pronounce", "diagram-zoom", "mermaid-render"]) {
  await build({
    entryPoints: [join(JS_DIR, `${name}.js`)],
    outfile: join(JS_DIR, `${name}.bundle.js`),
    bundle: true,
    format: "iife",
    target: ["es2020"],
    minify: true,
    legalComments: "none",
    banner: {
      js: "/* AUTO-GENERATED by scripts/bundle-js.mjs (esbuild) — do not edit. */",
    },
  });
  console.log(`bundle-js: public/js/${name}.js → public/js/${name}.bundle.js`);
}

// Hashed copies of the scripts every navigation loads (lib/hashed-scripts.js),
// served immutable from /js/h/ (server/static-cache.ts); the layout points at
// them through lib/js-assets.ts. The folder is rebuilt from scratch so it
// never piles up old hashes.
const HASHED_DIR = join(JS_DIR, "h");
rmSync(HASHED_DIR, { recursive: true, force: true });
mkdirSync(HASHED_DIR, { recursive: true });
for (const file of HASHED_SCRIPTS) {
  const bytes = readFileSync(join(JS_DIR, file));
  writeFileSync(join(HASHED_DIR, hashedScriptName(file, bytes)), bytes);
}
console.log(`bundle-js: ${HASHED_SCRIPTS.length} hashed copies → public/js/h/`);
