/** OWID's aggregate entities a block may name, with their French label. */
export const OWID_AGGREGATES: Record<string, string> = {
  World: "Monde",
  Africa: "Afrique",
  Asia: "Asie",
  Europe: "Europe",
  "North America": "Amérique du Nord",
  "South America": "Amérique du Sud",
  Oceania: "Océanie",
  "European Union (27)": "Union européenne",
  "High-income countries": "Pays à revenu élevé",
  "Low-income countries": "Pays à faible revenu",
};

const fold = (s: string) =>
  s.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase().replace(/[^a-z0-9]+/g, " ").trim();

const BY_KEY = new Map<string, { code: string; owid: string | null; fr: string }>();
for (const [iso3, iso2, , fr] of COUNTRIES) {
  const v = { code: iso3, owid: null, fr };
  BY_KEY.set(fold(iso3), v);
  BY_KEY.set(fold(iso2), v);
  BY_KEY.set(fold(fr), v);
}
for (const [en, fr] of Object.entries(OWID_AGGREGATES)) {
  const v = { code: "", owid: en, fr };
  BY_KEY.set(fold(en), v);
  BY_KEY.set(fold(fr), v);
}
BY_KEY.set("owid wrl", BY_KEY.get("world")!);

/**
 * Resolves one name from a vault block: an ISO code (`PNG`, `PG`), a French
 * country name (`Papouasie-Nouvelle-Guinée`, accents and case ignored) or an
 * OWID aggregate (`Monde`, `World`). `code` is the ISO alpha-3 (empty for an
 * aggregate, which OWID keys by its English `owid` name instead).
 */
export function resolveCountry(
  name: string,
): { code: string; owid: string | null; fr: string } | null {
  return BY_KEY.get(fold(name)) ?? null;
}

/** French name for an ISO alpha-3 code, or the code itself. */
export function countryFr(iso3: string): string {
  return BY_KEY.get(fold(iso3))?.fr ?? iso3;
}
