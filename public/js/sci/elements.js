/** Grid position: { row 1–7 for periods, 9–10 for the f-block rows; col 1–18 }. */
export function position(z) {
  if (z === 1) return { row: 1, col: 1 };
  if (z === 2) return { row: 1, col: 18 };
  const blocks = [
    [3, 10, 2],
    [11, 18, 3],
  ];
  for (const [a, b, row] of blocks) {
    if (z >= a && z <= b) {
      const i = z - a;
      return { row, col: i < 2 ? i + 1 : i + 10 };
    }
  }
  if (z <= 36) return { row: 4, col: z - 18 };
  if (z <= 54) return { row: 5, col: z - 36 };
  if (z >= 57 && z <= 71) return { row: 9, col: z - 57 + 3 };
  if (z >= 89 && z <= 103) return { row: 10, col: z - 89 + 3 };
  if (z <= 86) return { row: 6, col: z <= 56 ? z - 54 : z - 68 };
  return { row: 7, col: z <= 88 ? z - 86 : z - 100 };
}
